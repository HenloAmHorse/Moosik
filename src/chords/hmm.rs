const CHANGE_PENALTY: f64 = 30.0;

/// Chord segments `(first frame, end frame, chord)` from per-frame head
/// probabilities (see `net::HEADS`).
/// Segments as (first frame, end frame, chord, confidence): the mean
/// probability the triad head gave that chord's triad over the segment.
pub fn decode(probs: &[[f32; 100]]) -> Vec<(usize, usize, &'static str, f32)> {
    let t = probs.len();
    if t == 0 {
        return Vec::new();
    }
    let n = CHORDS.len();
    let starts = [0usize, 73, 86, 90, 94, 97];
    let ln = |v: f32| (v as f64).ln();
    let obs = |p: &[f32; 100], c: usize| -> f64 {
        let a = CHORDS[c].1;
        let mut s = ln(p[a[0] as usize]) + ln(p[starts[1] + a[1] as usize]);
        for i in 2..6 {
            if a[i] >= 0 {
                s += ln(p[starts[i] + a[i] as usize]);
            }
        }
        s
    };
    let mut dp: Vec<f64> = (0..n).map(|c| if c == 0 { obs(&probs[0], 0) } else { f64::NEG_INFINITY }).collect();
    let mut back = vec![0u16; t * n];
    let argmax = |v: &[f64]| (0..v.len()).fold(0, |b, i| if v[i] > v[b] { i } else { b });
    for ti in 1..t {
        let best = argmax(&dp);
        let change = dp[best] - CHANGE_PENALTY;
        let next: Vec<f64> = (0..n)
            .map(|c| {
                let stay = dp[c] > change;
                back[ti * n + c] = if stay { c } else { best } as u16;
                (if stay { dp[c] } else { change }) + obs(&probs[ti], c)
            })
            .collect();
        dp = next;
    }
    let mut path = vec![0usize; t];
    path[t - 1] = argmax(&dp);
    for ti in (0..t - 1).rev() {
        path[ti] = back[(ti + 1) * n + path[ti + 1]] as usize;
    }
    let mut out: Vec<(usize, usize, &'static str, f32)> = Vec::new();
    for (ti, &c) in path.iter().enumerate() {
        let p = probs[ti][CHORDS[c].1[0] as usize];
        match out.last_mut() {
            Some(last) if last.2 == CHORDS[c].0 => {
                last.1 = ti + 1;
                last.3 += p;
            }
            _ => out.push((ti, ti + 1, CHORDS[c].0, p)),
        }
    }
    out.iter_mut().for_each(|s| s.3 /= (s.1 - s.0) as f32);
    out
}
